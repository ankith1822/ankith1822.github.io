function openProductImage(productId) {

    const product =
        products.find(item => item.id === productId);

    if (!product) return;

    const modal =
        document.getElementById("image-lightbox");

    const image =
        document.getElementById("lightbox-image");

    const name =
        document.getElementById("lightbox-name");

    const price =
        document.getElementById("lightbox-price");

    if (!modal || !image || !name || !price) {
        return;
    }

    image.src = product.image;

    image.alt = product.name;

    name.textContent = product.name;

    const displayPrice =
        product.offerPrice !== null
            ? product.offerPrice
            : product.actualPrice;

    price.textContent =
        `₹${displayPrice}`;

    modal.classList.add("active");

    document.body.classList.add("lightbox-open");
}


function closeProductImage(event) {

    const modal =
        document.getElementById("image-lightbox");

    if (!modal) return;

    // Close only when clicking the dark background
    if (event && event.target !== modal) {
        return;
    }

    modal.classList.remove("active");

    document.body.classList.remove("lightbox-open");
}
