const productQuantities = {};


function changeProductQuantity(productId, change) {

    if (!productQuantities[productId]) {
        productQuantities[productId] = 1;
    }

    productQuantities[productId] += change;

    if (productQuantities[productId] < 1) {
        productQuantities[productId] = 1;
    }

    const quantityElement =
        document.getElementById(`product-qty-${productId}`);

    if (quantityElement) {
        quantityElement.value =
            productQuantities[productId];
    }
}




function addProductWithQuantity(productId) {

    const product = products.find(
        item => item.id === productId
    );

    if (!product) {
        console.error("Product not found:", productId);
        return;
    }

    const quantity =
        productQuantities[productId] || 1;

    const existingItem =
        cart.find(item => item.id === productId);

    if (existingItem) {
        existingItem.quantity += quantity;
    } else {
        cart.push({
            id: productId,
            name: product.name,
            quantity: quantity
        });
    }

    // Reset quantity selector
    productQuantities[productId] = 1;

    const quantityElement =
        document.getElementById(`product-qty-${productId}`);

    if (quantityElement) {
        quantityElement.textContent = "1";
    }

    // Update cart
updateCart();

showCartToast(product.name, quantity);

console.log(
    "Added to cart:",
    product.name,
    quantity
);
}
function showCartToast(productName, quantity) {

    const toast =
        document.getElementById("cart-toast");

    const message =
        document.getElementById("cart-toast-message");

    if (!toast) return;

    if (message) {

        message.textContent =
            quantity > 1
                ? `${quantity} × ${productName} added`
                : `${productName} added`;

    }

    toast.classList.add("show");

    clearTimeout(window.cartToastTimer);

    window.cartToastTimer =
        setTimeout(() => {

            toast.classList.remove("show");

        }, 2500);
}

