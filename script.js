function searchProducts() {

    const searchInput =
        document.getElementById("search-input");

    if (!searchInput) return;

    const searchText =
        searchInput.value
            .toLowerCase()
            .trim();

    const filteredProducts =
        products.filter(product =>
            product.name
                .toLowerCase()
                .includes(searchText) ||

            product.category
                .toLowerCase()
                .includes(searchText)
        );

    displayProducts(filteredProducts);
}


