function displayCart() {

    const cartItems =
        document.getElementById("cart-items");

    const cartTotal =
        document.getElementById("cart-total");

    const modalCount =
        document.getElementById("cart-count-modal");


    if (!cartItems) return;


    cartItems.innerHTML = "";


    // EMPTY CART

    if (cart.length === 0) {

        cartItems.innerHTML = `
            <div class="empty-cart">

                <div class="empty-cart-icon">
                    🛒
                </div>

                <h3>Your cart is empty</h3>

                <p>
                    Add some crackers to your cart.
                </p>

            </div>
        `;


        if (cartTotal) {
            cartTotal.textContent = "₹0";
        }


        if (modalCount) {
            modalCount.textContent = "0";
        }


        return;
    }


    let total = 0;


    // TOTAL QUANTITY

    const totalQuantity =
        cart.reduce(
            (sum, item) => sum + item.quantity,
            0
        );


    if (modalCount) {
        modalCount.textContent = totalQuantity;
    }


    // DISPLAY PRODUCTS

    cart.forEach((item, index) => {

        const product =
            products.find(
                product => product.id === item.id
            );


        if (!product) return;


        const unitPrice =
            product.offerPrice !== null
                ? product.offerPrice
                : product.actualPrice;


        const itemTotal =
            unitPrice * item.quantity;


        total += itemTotal;


        const cartItem =
            document.createElement("div");


        cartItem.className = "cart-product";


        cartItem.innerHTML = `

            <!-- PRODUCT IMAGE -->

            <div class="cart-product-image">

                <img
                    src="${product.image}"
                    alt="${product.name}"
                >

            </div>


            <!-- PRODUCT DETAILS -->

            <div class="cart-product-info">

                <h3>
                    ${product.name}
                </h3>


                <div class="cart-product-price">

                    <strong>
                        ₹${unitPrice}
                    </strong>

                    <span>
                        ₹${product.actualPrice}
                    </span>

                </div>


                <!-- QUANTITY -->

                <div class="cart-product-quantity">

                    <button
                        onclick="changeQuantity(${index}, -1)"
                    >
                        −
                    </button>


                    <span>
                        ${item.quantity}
                    </span>


                    <button
                        onclick="changeQuantity(${index}, 1)"
                    >
                        +
                    </button>

                </div>

            </div>


            <!-- ITEM TOTAL -->

            <div class="cart-product-total">

                <button
                    class="cart-delete"
                    onclick="removeFromCart(${index})"
                >
                    🗑
                </button>


                <strong>
                    ₹${itemTotal}
                </strong>

            </div>

        `;


        cartItems.appendChild(cartItem);

    });


    if (cartTotal) {

        cartTotal.textContent =
            `₹${total}`;

    }

}
