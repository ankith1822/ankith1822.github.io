function sortProducts(sortType) {

    let sortedProducts =
        [...currentProductList];

    if (sortType === "price-low") {

        sortedProducts.sort(
            (a, b) =>
                (a.offerPrice ?? a.actualPrice) -
                (b.offerPrice ?? b.actualPrice)
        );

    }

    else if (sortType === "price-high") {

        sortedProducts.sort(
            (a, b) =>
                (b.offerPrice ?? b.actualPrice) -
                (a.offerPrice ?? a.actualPrice)
        );

    }

    else if (sortType === "name-az") {

        sortedProducts.sort(
            (a, b) =>
                a.name.localeCompare(b.name)
        );

    }

    else if (sortType === "name-za") {

        sortedProducts.sort(
            (a, b) =>
                b.name.localeCompare(a.name)
        );

    }

    else {

        sortedProducts =
            [...currentProductList];

    }

    displayProducts(sortedProducts);
}
